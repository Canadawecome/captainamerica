#!/usr/bin/env python3
"""Explicit opt-in OpusClip POST. Does not yet poll/download exports.

API payload is generated by GPT-planned director. Production integrations must
validate account-specific provider fields/quotas and implement retries and webhook handling.
"""
from __future__ import annotations
import argparse,json,os,urllib.request,urllib.error
from pathlib import Path
try:
    from dotenv import load_dotenv
    load_dotenv(Path(__file__).parent / '.env')
except ImportError:
    pass

def submit(jobs:Path,output:Path,execute=False,max_projects=8):
    data=json.loads(jobs.read_text(encoding='utf8'))
    if data.get('schema_version') not in ('podcast-v1','podcast-v1.1'):raise ValueError('Unsupported jobs schema')
    if not execute:return {'status':'DRY_RUN','jobs':len(data['jobs']),'budget_limit_projects':max_projects}
    if len(data['jobs'])>max_projects:raise ValueError('OPUS_PROJECT_BUDGET_EXCEEDED: review list; increase --max-projects explicitly')
    token=os.environ.get('OPUSCLIP_API_KEY')
    if not token:raise ValueError('OPUSCLIP_API_KEY missing')
    if output.exists():raise FileExistsError('Refuse accidental resubmission of existing results')
    results=[]
    for job in data['jobs']:
        req=urllib.request.Request('https://api.opus.pro/api/clip-projects',method='POST',
              headers={'Authorization':'Bearer '+token,'Content-Type':'application/json','User-Agent':'Mozilla/5.0 (Windows NT 10.0; Win64; x64)'},
              data=json.dumps(job['request']).encode('utf8'))
        try:
            with urllib.request.urlopen(req,timeout=75) as r:payload=json.loads(r.read())
            results.append({'group_id':job.get('group_id'),'candidate_ids':job.get('candidate_ids',[job.get('candidate_id')]),'status':'SUBMITTED','result':payload})
        except urllib.error.HTTPError as e:
            err_body = e.read().decode('utf8', errors='ignore')
            results.append({'group_id':job.get('group_id'),'candidate_ids':job.get('candidate_ids',[job.get('candidate_id')]),'status':'ERROR','http_code':e.code, 'error_body': err_body})
        output.parent.mkdir(parents=True,exist_ok=True)
        output.write_text(json.dumps({'schema_version':data['schema_version'],'results':results},indent=2),encoding='utf8')
    return {'status':'SUBMISSIONS_ATTEMPTED','results':len(results)}

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--jobs',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    p.add_argument('--execute',action='store_true');p.add_argument('--max-projects',type=int,default=8);a=p.parse_args()
    print(json.dumps(submit(a.jobs,a.output,a.execute,a.max_projects),indent=2))
